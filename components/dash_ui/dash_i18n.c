void dash_i18n_set(dash_lang_t lang)
{
    current = lang == DASH_LANG_EN ? DASH_LANG_EN : DASH_LANG_ZH;
}

dash_lang_t dash_i18n_get(void)
{
    return current;
}

const char *dash_tr(dash_str_t id)
{
    if ((unsigned)id >= S_COUNT) {
        return "?";
    }
    const char *s = table[id][current];
    return s ? s : table[id][DASH_LANG_EN];
}
