#!/usr/bin/env python3
"""assets/cat/*.txt (+ palette.cfg, looks.cfg) -> components/dash_ui/sprites/dash_sprites.{c,h}

Each 32x32 layer becomes 4-bit palette indices (index 0 = transparent).
A "look" is an ordered list of layers the compositor draws bottom-up.
Run after editing the art:  python3 scripts/cat_art.py && python3 scripts/gen_sprites.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "cat"
OUT = ROOT / "components" / "dash_ui" / "sprites"
W = H = 32


def ident(name):
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()


palette = {}
for line in (SRC / "palette.cfg").read_text().splitlines():
    ch, col = line.split(" ", 1)
    palette[ch] = None if col == "-" else col
layers = {p.stem: [row for row in p.read_text().splitlines() if row] for p in sorted(SRC.glob("*.txt"))}
used = sorted({c for rows in layers.values() for row in rows for c in row if c != "."})
if len(used) > 15:
    raise SystemExit(f"too many colours for 4-bit: {used}")
index = {".": 0, **{c: i + 1 for i, c in enumerate(used)}}
looks = []
for line in (SRC / "looks.cfg").read_text().splitlines():
    label, names = line.split(":", 1)
    looks.append((label.strip(), names.split()))

OUT.mkdir(parents=True, exist_ok=True)
names = list(layers)
h = ["/* Generated by scripts/gen_sprites.py from assets/cat -- do not edit. */",
     "#pragma once", "#include <stdint.h>", "",
     f"#define DASH_SPR_W {W}", f"#define DASH_SPR_H {H}", "", "typedef enum {"]
h += [f"    DASH_SPR_{ident(n)}," for n in names] + ["    DASH_SPR_COUNT", "} dash_sprite_id_t;", "", "typedef enum {"]
h += [f"    DASH_LOOK_{ident(lab)}," for lab, _ in looks] + ["    DASH_LOOK_COUNT", "} dash_look_id_t;", ""]
h += ["#define DASH_LOOK_MAX_LAYERS 5",
      "typedef struct {", "    uint8_t n;", "    uint8_t layer[DASH_LOOK_MAX_LAYERS];", "} dash_look_t;", "",
      "extern const uint32_t dash_sprite_palette[16]; /* ARGB8888, [0] = transparent */",
      "extern const uint8_t dash_sprites[DASH_SPR_COUNT][DASH_SPR_W * DASH_SPR_H / 2]; /* 4 bpp, high nibble first */",
      "extern const dash_look_t dash_looks[DASH_LOOK_COUNT];",
      "extern const char *const dash_look_names[DASH_LOOK_COUNT];", ""]
(OUT / "dash_sprites.h").write_text("\n".join(h))

c = ["/* Generated by scripts/gen_sprites.py from assets/cat -- do not edit. */",
     '#include "dash_sprites.h"', "", "const uint32_t dash_sprite_palette[16] = {", "    0x00000000,"]
for ch in used:
    c.append(f"    0xFF{palette[ch]},  /* {ch} */")
c += [f"    0x00000000," for _ in range(15 - len(used))] + ["};", "",
      "const uint8_t dash_sprites[DASH_SPR_COUNT][DASH_SPR_W * DASH_SPR_H / 2] = {"]
for n in names:
    rows = layers[n]
    assert len(rows) == H and all(len(r) == W for r in rows), n
    flat = [index[ch] for row in rows for ch in row]
    data = [(flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2)]
    c.append(f"    [DASH_SPR_{ident(n)}] = {{")
    for i in range(0, len(data), 16):
        c.append("        " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    c.append("    },")
c += ["};", "", "const dash_look_t dash_looks[DASH_LOOK_COUNT] = {"]
for lab, ns in looks:
    assert len(ns) <= 5, lab
    c.append(f"    [DASH_LOOK_{ident(lab)}] = {{{len(ns)}, {{" + ", ".join(f"DASH_SPR_{ident(n)}" for n in ns) + "}},")
c += ["};", "", "const char *const dash_look_names[DASH_LOOK_COUNT] = {"]
c += [f'    "{lab}",' for lab, _ in looks] + ["};", ""]
(OUT / "dash_sprites.c").write_text("\n".join(c))
print(f"{len(names)} layers, {len(looks)} looks, {len(used)} colours -> {OUT}")
