#!/usr/bin/env python3
"""Generate offline 2026..2099 dates from Hong Kong Observatory annual tables.

Default operation is offline and reproducible. --refresh-hko downloads the public
official source tables and keeps just six dates and each source's SHA-256.
Do not use LVGL's solar-term table: e.g. its 2028 winter solstice is incorrect.
Source: https://www.hko.gov.hk/en/gts/time/conversion.htm
"""
import argparse
import concurrent.futures
import datetime as dt
import hashlib
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA = ROOT / "assets/calendar/holidays_2026_2099.json"
URL = "https://www.hko.gov.hk/en/gts/time/calendar/text/files/T{year}e.txt"
TARGETS = [(1, 1), (1, 15), (5, 5), (7, 7), (9, 9)]


def extract(year, source):
    month, leap = 0, False
    found = {}
    for line in source.splitlines():
        match = re.match(r"^(\d{4}/\d{1,2}/\d{1,2})\s{2,}(.+?)\s{2,}(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday)", line)
        if not match:
            continue
        stamp, lunar = match.group(1, 2)
        date = dt.date(*map(int, stamp.split("/")))
        if date.year != year:
            raise ValueError("unexpected source year")
        if "Winter Solstice" in line:
            found["winter"] = date
        if m := re.search(r"(\d+)(?:st|nd|rd|th) Lunar Month", lunar):
            new_month = int(m[1])
            # The HKO English text repeats the month number for an intercalary
            # month, without necessarily printing the word "leap".
            leap = new_month == month or bool(re.search(r"leap|intercalary", lunar, re.I))
            month, day = new_month, 1
        elif lunar.strip().isdigit():
            day = int(lunar)
        else:
            raise ValueError(f"unknown lunar field: {lunar}")
        if not leap and (month, day) in TARGETS:
            if (month, day) in found:
                raise ValueError(f"duplicate lunar festival in {year}: {lunar}")
            found[month, day] = date
    days = [found[k] for k in TARGETS]+[found["winter"]]
    if len(set(days)) != 6:
        raise ValueError("invalid holiday dates")
    return days


def download(year):
    cache = ROOT / "build-sim/hko-calendar-source" / f"T{year}e.txt"
    with urllib.request.urlopen(URL.format(year=year), timeout=30) as response:
        raw = response.read()
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_bytes(raw)
    return str(year), {"dates": [d.isoformat() for d in extract(year, raw.decode("utf-8-sig"))],
                       "sha256": hashlib.sha256(raw).hexdigest()}


def dates():
    data = json.loads(DATA.read_text())
    for year in range(2026, 2100):
        days = [dt.date.fromisoformat(x) for x in data["years"][str(year)]["dates"]]
        if len(days) != 6 or any(d.year != year for d in days):
            raise ValueError("invalid offline calendar")
        yield year, days


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-hko", action="store_true")
    args = parser.parse_args()
    if args.refresh_hko:
        with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
            years = dict(pool.map(download, range(2026, 2100)))
        DATA.parent.mkdir(parents=True, exist_ok=True)
        DATA.write_text(json.dumps({"source_template": URL, "order": ["spring", "lantern", "dragon", "qixi", "chongyang", "solstice"],
                                   "years": years}, ensure_ascii=False, indent=2)+"\n")
    rows = ["/* Generated by scripts/gen_holidays.py from Hong Kong Observatory data. Do not edit. */"]
    for year, days in dates():
        rows.append("    {"+", ".join(str((d-dt.date(year, 1, 1)).days) for d in days)+"}, /* "+str(year)+" */")
    (ROOT / "components/dash_model/dash_holiday_dates.inc").write_text("\n".join(rows)+"\n")
